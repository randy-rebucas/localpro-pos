import { beforeEach, describe, expect, it, vi } from 'vitest';
import { NextRequest } from 'next/server';

const mocks = vi.hoisted(() => ({
  aggregate: vi.fn(),
  endingGT: vi.fn(),
  findOne: vi.fn(),
  create: vi.fn(),
  tenantLean: vi.fn(),
}));

vi.mock('@/lib/mongodb', () => ({ default: vi.fn().mockResolvedValue(undefined) }));
vi.mock('@/lib/auth', () => ({ requireAuth: vi.fn().mockResolvedValue({ userId: 'user-1', tenantId: 'tenant-a', role: 'manager' }) }));
vi.mock('@/lib/api-tenant', () => ({ getTenantIdFromRequest: vi.fn().mockResolvedValue('tenant-a') }));
vi.mock('@/lib/permissions-server', () => ({ hasTenantPermission: vi.fn().mockResolvedValue(true) }));
vi.mock('@/lib/rate-limit', () => ({ checkRateLimit: () => ({ allowed: true, remaining: 9, resetAfterMs: 0 }) }));
vi.mock('@/lib/validation-translations', () => ({
  getValidationTranslatorFromRequest: vi.fn().mockResolvedValue((_key: string, fallback: string) => fallback),
}));
vi.mock('@/lib/audit', () => ({ createAuditLog: vi.fn().mockResolvedValue(undefined), AuditActions: {} }));
vi.mock('@/lib/bir-readings', () => ({ getDailySalesAggregate: mocks.aggregate, getGrandTotalAtDayEnd: mocks.endingGT }));
vi.mock('@/models/Tenant', () => ({
  default: {
    findById: () => ({ select: () => ({ lean: mocks.tenantLean }) }),
    findByIdAndUpdate: vi.fn().mockResolvedValue(undefined),
  },
}));
vi.mock('@/models/ZReading', () => ({
  default: {
    findOne: (...args: unknown[]) => ({ populate: () => ({ lean: () => mocks.findOne(...args) }) }),
    create: mocks.create,
  },
}));

import { POST } from '@/app/api/reports/z-reading/route';

const post = (body: Record<string, unknown>) =>
  POST(new NextRequest('http://localhost/api/reports/z-reading', { method: 'POST', body: JSON.stringify(body) }));

describe('POST /api/reports/z-reading business day', () => {
  beforeEach(() => {
    vi.clearAllMocks();
    mocks.tenantLean.mockResolvedValue({ grandTotalSales: 1000, settings: {} });
    mocks.findOne.mockResolvedValue(null);
    mocks.create.mockResolvedValue({ _id: 'z1' });
    mocks.endingGT.mockResolvedValue(1000);
    mocks.aggregate.mockResolvedValue({ grossSales: 100, vatableSales: 0, vatAmount: 0, vatExemptSales: 0, zeroRatedSales: 0, discountTotal: 0, transactionCount: 1, voidCount: 0, refundCount: 0, refundTotal: 0, refundVatAmount: 0, netSales: 100 });
  });

  it('stamps a new reading at midnight Manila when the store has no timezone set', async () => {
    await post({ date: '2026-11-07' });

    expect(mocks.create.mock.calls[0][0].businessDate).toEqual(new Date('2026-11-06T16:00:00.000Z'));
    expect(mocks.aggregate).toHaveBeenCalledWith('tenant-a', '2026-11-07', 'Asia/Manila');
  });

  it("uses the store's own timezone when it has one", async () => {
    mocks.tenantLean.mockResolvedValue({ grandTotalSales: 1000, settings: { timezone: 'America/New_York' } });

    await post({ date: '2026-11-10' });

    expect(mocks.create.mock.calls[0][0].businessDate).toEqual(new Date('2026-11-10T05:00:00.000Z'));
  });

  it('finds a reading saved under the old UTC stamp, so a day can never get a second one', async () => {
    mocks.findOne.mockImplementation((query: { businessDate: { $gte: Date; $lte: Date } }) => {
      const legacyStamp = new Date('2026-11-07T00:00:00.000Z');
      const { $gte, $lte } = query.businessDate;
      return Promise.resolve(legacyStamp >= $gte && legacyStamp <= $lte ? { _id: 'legacy' } : null);
    });

    const res = await post({ date: '2026-11-07' });
    const body = await res.json();

    expect(body).toMatchObject({ success: true, reprint: true, data: { _id: 'legacy' } });
    expect(mocks.create).not.toHaveBeenCalled();
  });

  it('takes the Grand Total at the end of the day being read, and credits the user', async () => {
    mocks.endingGT.mockResolvedValue(800);

    await post({ date: '2026-11-02' });

    expect(mocks.create.mock.calls[0][0]).toMatchObject({ endingGT: 800, beginningGT: 700, generatedBy: 'user-1', autoGenerated: false });
  });

  it('rejects a date it cannot read', async () => {
    const res = await post({ date: 'garbage' });

    expect(res.status).toBe(400);
    expect(mocks.create).not.toHaveBeenCalled();
  });
});
