import Tenant from '@/models/Tenant';
import ZReading, { type IZReading } from '@/models/ZReading';
import { getDailySalesAggregate, getGrandTotalAtDayEnd } from '@/lib/bir-readings';
import { DEFAULT_TENANT_TIMEZONE, getTenantDayBoundaries } from '@/lib/timezone';

export interface GenerateZReadingOptions {
  tenantId: string;
  /** Any moment in the business day, or 'YYYY-MM-DD' to name the day exactly. */
  day: Date | string;
  /** Who asked for it. Left out, the reading is marked as automatic. */
  generatedBy?: string;
  /** Make no reading for a day with no sales, voids or refunds. */
  skipEmptyDay?: boolean;
}

export interface ZReadingResult {
  reading: Pick<
    IZReading,
    '_id' | 'grossSales' | 'netSales' | 'refundTotal' | 'discountTotal' | 'vatAmount' | 'beginningGT' | 'endingGT' | 'transactionCount' | 'voidCount'
  >;
  /** False when the day already had a reading, which is returned as it was saved. */
  created: boolean;
  businessDate: Date;
}

/**
 * Locks in a business day's totals, once. Both the Reports page and the automatic
 * job go through here, so a day can only ever get one reading whichever comes first.
 * Returns null only when skipEmptyDay applies.
 */
export async function generateZReading(options: GenerateZReadingOptions & { skipEmptyDay: true }): Promise<ZReadingResult | null>;
export async function generateZReading(options: GenerateZReadingOptions): Promise<ZReadingResult>;
export async function generateZReading({
  tenantId,
  day,
  generatedBy,
  skipEmptyDay,
}: GenerateZReadingOptions): Promise<ZReadingResult | null> {
  const tenant = await Tenant.findById(tenantId).select('grandTotalSales settings.timezone').lean();
  const readAt = new Date();
  const timezone = tenant?.settings?.timezone || DEFAULT_TENANT_TIMEZONE;
  const { start: businessDate, end: dayEnd } = getTenantDayBoundaries(day, timezone);

  // A range, because readings saved before business days followed the store's
  // timezone are stamped at a different instant within the same day
  const findExisting = () =>
    ZReading.findOne({ tenantId, businessDate: { $gte: businessDate, $lte: dayEnd } })
      .populate('generatedBy', 'name email')
      .lean();

  const existing = await findExisting();
  if (existing) return { reading: existing, created: false, businessDate };

  const aggregate = await getDailySalesAggregate(tenantId, day, timezone);
  if (skipEmptyDay && !aggregate.transactionCount && !aggregate.voidCount && !aggregate.refundCount) {
    return null;
  }

  const endingGT = await getGrandTotalAtDayEnd(tenantId, dayEnd, tenant?.grandTotalSales ?? 0, readAt);
  const beginningGT = Math.max(0, endingGT - aggregate.grossSales);

  try {
    const reading = await ZReading.create({
      tenantId,
      businessDate,
      beginningGT,
      endingGT,
      grossSales: aggregate.grossSales,
      vatableSales: aggregate.vatableSales,
      vatAmount: aggregate.vatAmount,
      vatExemptSales: aggregate.vatExemptSales,
      zeroRatedSales: aggregate.zeroRatedSales,
      discountTotal: aggregate.discountTotal,
      transactionCount: aggregate.transactionCount,
      voidCount: aggregate.voidCount,
      refundCount: aggregate.refundCount,
      refundTotal: aggregate.refundTotal,
      refundVatAmount: aggregate.refundVatAmount,
      netSales: aggregate.netSales,
      generatedBy,
      autoGenerated: !generatedBy,
      generatedAt: new Date(),
    });
    return { reading, created: true, businessDate };
  } catch (createErr: unknown) {
    // Unique index race: another request generated it first, so return that one.
    if (createErr instanceof Error && 'code' in createErr && (createErr as { code?: number }).code === 11000) {
      const race = await findExisting();
      if (race) return { reading: race, created: false, businessDate };
    }
    throw createErr;
  }
}
