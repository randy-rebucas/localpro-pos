#!/usr/bin/env bash
#
# Provision PostgreSQL 17 + PgBouncer + pgBackRest for 1POS on a fresh Ubuntu 24.04 VPS.
# Phase 1 of the PostgreSQL migration — see infra/postgres/README.md and docs/postgres-migration.md.
#
# Usage (on the VPS, from a checkout or copy of infra/postgres/):
#   cp provision.env.example provision.env   # fill it in
#   sudo ./provision.sh provision.env
#
# Safe to re-run: packages and config are re-applied, generated passwords are
# kept in /root/1pos-db-credentials.env and reused.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="${1:-$SCRIPT_DIR/provision.env}"
CREDENTIALS_FILE=/root/1pos-db-credentials.env
PG_VERSION=17
PG_CONF_DIR="/etc/postgresql/$PG_VERSION/main"

print_step() { echo -e "\n\033[1;34m==> $1\033[0m"; }
print_info() { echo "    $1"; }
print_warning() { echo -e "    \033[1;33m⚠ $1\033[0m"; }
die() { echo -e "\033[1;31m✗ $1\033[0m" >&2; exit 1; }

# ─── Preflight ────────────────────────────────────────────────────────────────

[[ $EUID -eq 0 ]] || die "Run as root (sudo $0 $ENV_FILE)"
[[ -f "$ENV_FILE" ]] || die "Config not found: $ENV_FILE (copy provision.env.example)"
# shellcheck disable=SC1090
source "$ENV_FILE"

. /etc/os-release
[[ "$ID" == "ubuntu" ]] || print_warning "Tested on Ubuntu 24.04, found $PRETTY_NAME"

DB_NAME="${DB_NAME:-localpro_pos}"
TLS_MODE="${TLS_MODE:-letsencrypt}"
PGBOUNCER_ALLOW_FROM="${PGBOUNCER_ALLOW_FROM:-any}"
S3_URI_STYLE="${S3_URI_STYLE:-host}"
[[ -n "${DB_HOSTNAME:-}" ]] || die "DB_HOSTNAME is required (e.g. db.example.com)"
if [[ "$TLS_MODE" == "letsencrypt" && -z "${LETSENCRYPT_EMAIL:-}" ]]; then
  die "LETSENCRYPT_EMAIL is required when TLS_MODE=letsencrypt"
fi

BACKUPS_ENABLED=false
if [[ -n "${S3_BUCKET:-}" && -n "${S3_ACCESS_KEY_ID:-}" && -n "${S3_SECRET_ACCESS_KEY:-}" ]]; then
  BACKUPS_ENABLED=true
  [[ -n "${S3_ENDPOINT:-}" && -n "${S3_REGION:-}" ]] || die "S3_ENDPOINT and S3_REGION are required with S3_BUCKET"
else
  print_warning "S3_* not set — WAL archiving and backups will be DISABLED. Do not go to production like this."
fi

# ─── 1. Packages ──────────────────────────────────────────────────────────────

print_step "Installing PostgreSQL $PG_VERSION, PgBouncer, pgBackRest (PGDG repository)"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq curl ca-certificates gnupg gettext-base openssl ufw >/dev/null
install -d /usr/share/postgresql-common/pgdg
curl -fsSL -o /usr/share/postgresql-common/pgdg/apt.postgresql.org.asc \
  https://www.postgresql.org/media/keys/ACCC4CF8.asc
echo "deb [signed-by=/usr/share/postgresql-common/pgdg/apt.postgresql.org.asc] https://apt.postgresql.org/pub/repos/apt ${VERSION_CODENAME}-pgdg main" \
  > /etc/apt/sources.list.d/pgdg.list
apt-get update -qq
apt-get install -y -qq "postgresql-$PG_VERSION" pgbouncer pgbackrest >/dev/null
print_info "$(psql --version), $(pgbouncer --version | head -1), $(pgbackrest version)"

# ─── 2. PostgreSQL configuration ──────────────────────────────────────────────

print_step "Configuring PostgreSQL"
MEM_MB=$(awk '/MemTotal/ {print int($2 / 1024)}' /proc/meminfo)
MAINT_MB=$((MEM_MB / 16)); (( MAINT_MB > 1024 )) && MAINT_MB=1024
export PG_SHARED_BUFFERS="$((MEM_MB / 4))MB"
export PG_EFFECTIVE_CACHE_SIZE="$((MEM_MB * 3 / 4))MB"
export PG_MAINTENANCE_WORK_MEM="${MAINT_MB}MB"
print_info "RAM ${MEM_MB}MB → shared_buffers $PG_SHARED_BUFFERS, effective_cache_size $PG_EFFECTIVE_CACHE_SIZE"

envsubst '${PG_SHARED_BUFFERS} ${PG_EFFECTIVE_CACHE_SIZE} ${PG_MAINTENANCE_WORK_MEM}' \
  < "$SCRIPT_DIR/templates/postgresql.conf.tmpl" > "$PG_CONF_DIR/conf.d/1pos.conf"
if [[ "$BACKUPS_ENABLED" != true ]]; then
  sed -i "s/^archive_mode = on/archive_mode = off/" "$PG_CONF_DIR/conf.d/1pos.conf"
fi

cat > "$PG_CONF_DIR/pg_hba.conf" <<'EOF'
# Managed by infra/postgres/provision.sh
# TYPE  DATABASE  USER      ADDRESS        METHOD
local   all       postgres                 peer
local   all       all                      scram-sha-256
host    all       all       127.0.0.1/32   scram-sha-256
host    all       all       ::1/128        scram-sha-256
EOF
systemctl restart "postgresql@$PG_VERSION-main"

# ─── 3. Roles, database, extensions ───────────────────────────────────────────

print_step "Creating roles and database"
if [[ -f "$CREDENTIALS_FILE" ]]; then
  # shellcheck disable=SC1090
  source "$CREDENTIALS_FILE"
  print_info "Reusing passwords from $CREDENTIALS_FILE"
else
  POS_OWNER_PASSWORD=$(openssl rand -hex 24)
  POS_APP_PASSWORD=$(openssl rand -hex 24)
  POS_READONLY_PASSWORD=$(openssl rand -hex 24)
  BACKUP_CIPHER_PASS=$(openssl rand -hex 32)
  install -m 600 /dev/null "$CREDENTIALS_FILE"
  cat > "$CREDENTIALS_FILE" <<EOF
# Generated by provision.sh — keep a copy in your password manager.
# BACKUP_CIPHER_PASS is required to restore backups: losing it loses the backups.
POS_OWNER_PASSWORD=$POS_OWNER_PASSWORD
POS_APP_PASSWORD=$POS_APP_PASSWORD
POS_READONLY_PASSWORD=$POS_READONLY_PASSWORD
BACKUP_CIPHER_PASS=$BACKUP_CIPHER_PASS
EOF
  print_info "Generated passwords → $CREDENTIALS_FILE"
fi

sudo -u postgres psql -q \
  -v db_name="$DB_NAME" \
  -v owner_password="$POS_OWNER_PASSWORD" \
  -v app_password="$POS_APP_PASSWORD" \
  -v readonly_password="$POS_READONLY_PASSWORD" \
  -f "$SCRIPT_DIR/sql/roles.sql"
sudo -u postgres psql -q -d "$DB_NAME" -v ON_ERROR_STOP=1 -f "$SCRIPT_DIR/init/01-extensions.sql"

# ─── 4. TLS certificate for PgBouncer ─────────────────────────────────────────

print_step "TLS certificate ($TLS_MODE)"
install -d -o postgres -g postgres -m 700 /etc/pgbouncer/tls
if [[ "$TLS_MODE" == "letsencrypt" ]]; then
  apt-get install -y -qq certbot >/dev/null
  # Standalone renewal needs port 80; nothing else listens on it.
  ufw allow 80/tcp >/dev/null
  cat > /etc/letsencrypt/renewal-hooks/deploy/1pos-pgbouncer.sh <<EOF
#!/bin/sh
install -o postgres -g postgres -m 644 /etc/letsencrypt/live/$DB_HOSTNAME/fullchain.pem /etc/pgbouncer/tls/server.crt
install -o postgres -g postgres -m 600 /etc/letsencrypt/live/$DB_HOSTNAME/privkey.pem /etc/pgbouncer/tls/server.key
systemctl reload pgbouncer 2>/dev/null || true
EOF
  chmod 755 /etc/letsencrypt/renewal-hooks/deploy/1pos-pgbouncer.sh
  if [[ ! -d "/etc/letsencrypt/live/$DB_HOSTNAME" ]]; then
    certbot certonly --standalone --non-interactive --agree-tos \
      -m "$LETSENCRYPT_EMAIL" -d "$DB_HOSTNAME"
  fi
  /etc/letsencrypt/renewal-hooks/deploy/1pos-pgbouncer.sh
else
  if [[ ! -f /etc/pgbouncer/tls/server.crt ]]; then
    openssl req -x509 -newkey rsa:2048 -nodes -days 825 -subj "/CN=$DB_HOSTNAME" \
      -keyout /etc/pgbouncer/tls/server.key -out /etc/pgbouncer/tls/server.crt 2>/dev/null
    chown postgres:postgres /etc/pgbouncer/tls/server.*
    chmod 600 /etc/pgbouncer/tls/server.key
  fi
  print_warning "Self-signed certificate: clients must use sslmode=require (no hostname verification)"
fi

# ─── 5. PgBouncer ─────────────────────────────────────────────────────────────

print_step "Configuring PgBouncer (transaction pooling on :6432)"
export DB_NAME
envsubst '${DB_NAME}' < "$SCRIPT_DIR/templates/pgbouncer.ini.tmpl" > /etc/pgbouncer/pgbouncer.ini
# SCRAM verifiers (not plaintext). pos_owner is deliberately absent: migrations
# and ETL use the direct connection through an SSH tunnel.
sudo -u postgres psql -Atq -c \
  "SELECT format('\"%s\" \"%s\"', rolname, rolpassword) FROM pg_authid WHERE rolname IN ('pos_app', 'pos_readonly') ORDER BY rolname" \
  > /etc/pgbouncer/userlist.txt
chown postgres:postgres /etc/pgbouncer/pgbouncer.ini /etc/pgbouncer/userlist.txt
chmod 640 /etc/pgbouncer/pgbouncer.ini
chmod 600 /etc/pgbouncer/userlist.txt
systemctl enable pgbouncer >/dev/null
systemctl restart pgbouncer

# ─── 6. Firewall ──────────────────────────────────────────────────────────────

print_step "Firewall"
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
ufw allow OpenSSH >/dev/null
if [[ "$PGBOUNCER_ALLOW_FROM" == "any" ]]; then
  # Vercel functions have no fixed egress IPs (without Secure Compute);
  # TLS + SCRAM + long random passwords are the protection.
  ufw allow 6432/tcp >/dev/null
  print_info "PgBouncer :6432 open to all (TLS + SCRAM required); Postgres :5432 localhost only"
else
  for cidr in ${PGBOUNCER_ALLOW_FROM//,/ }; do
    ufw allow from "$cidr" to any port 6432 proto tcp >/dev/null
  done
  print_info "PgBouncer :6432 open to $PGBOUNCER_ALLOW_FROM; Postgres :5432 localhost only"
fi
ufw --force enable >/dev/null

# ─── 7. Backups (pgBackRest → S3) ─────────────────────────────────────────────

if [[ "$BACKUPS_ENABLED" == true ]]; then
  print_step "Configuring pgBackRest backups to s3://$S3_BUCKET/pgbackrest/1pos"
  export S3_ENDPOINT S3_REGION S3_BUCKET S3_ACCESS_KEY_ID S3_SECRET_ACCESS_KEY S3_URI_STYLE BACKUP_CIPHER_PASS
  install -d -o postgres -g postgres -m 750 /etc/pgbackrest /var/log/pgbackrest
  envsubst '${S3_ENDPOINT} ${S3_REGION} ${S3_BUCKET} ${S3_ACCESS_KEY_ID} ${S3_SECRET_ACCESS_KEY} ${S3_URI_STYLE} ${BACKUP_CIPHER_PASS}' \
    < "$SCRIPT_DIR/templates/pgbackrest.conf.tmpl" > /etc/pgbackrest/pgbackrest.conf
  chown postgres:postgres /etc/pgbackrest/pgbackrest.conf
  chmod 640 /etc/pgbackrest/pgbackrest.conf

  sudo -u postgres pgbackrest --stanza=1pos stanza-create
  sudo -u postgres pgbackrest --stanza=1pos check
  if ! sudo -u postgres pgbackrest --stanza=1pos info | grep -q "full backup"; then
    print_info "Taking initial full backup"
    sudo -u postgres pgbackrest --stanza=1pos --type=full backup
  fi

  cat > /etc/cron.d/1pos-pgbackrest <<'EOF'
# Managed by infra/postgres/provision.sh — times are server time (UTC)
# Full backup Sunday 18:00 UTC (02:00 Manila), differential the other days
0 18 * * 0   postgres pgbackrest --stanza=1pos --type=full backup
0 18 * * 1-6 postgres pgbackrest --stanza=1pos --type=diff backup
EOF
  chmod 644 /etc/cron.d/1pos-pgbackrest
fi

# ─── Summary ──────────────────────────────────────────────────────────────────

print_step "Done"
SSLMODE=$([[ "$TLS_MODE" == "letsencrypt" ]] && echo "verify-full" || echo "require")
cat <<EOF

  Passwords: $CREDENTIALS_FILE (root only)

  Vercel / app (pooled, through PgBouncer):
    DATABASE_URL=postgres://pos_app:<POS_APP_PASSWORD>@$DB_HOSTNAME:6432/$DB_NAME?sslmode=$SSLMODE

  Migrations / ETL (direct; open an SSH tunnel first):
    ssh -N -L 15432:localhost:5432 <user>@$DB_HOSTNAME
    DATABASE_URL_DIRECT=postgres://pos_owner:<POS_OWNER_PASSWORD>@localhost:15432/$DB_NAME

  Read-only (reports, verification):
    postgres://pos_readonly:<POS_READONLY_PASSWORD>@$DB_HOSTNAME:6432/$DB_NAME?sslmode=$SSLMODE

  Verify from your machine:  pnpm pg:health
EOF
